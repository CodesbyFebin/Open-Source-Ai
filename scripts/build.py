"""Generate README, docs pages, credits, search data and mkdocs nav from catalog/*.

Deterministic: output depends only on catalog/ files. Run: python scripts/build.py
"""
import json, os, glob, yaml

GEN = "<!-- GENERATED by scripts/build.py from catalog/. Do not edit by hand. -->\n"
SITE = "https://codesbyfebin.github.io/Open-Source-Ai/"
cats = yaml.safe_load(open("catalog/categories.yaml"))["categories"]
projects = yaml.safe_load(open("catalog/projects.yaml"))["projects"]
quick = json.load(open("catalog/quickstarts.json"))
ev = {}
for f in sorted(glob.glob("catalog/evidence/*.json")):
    e = json.load(open(f)); ev[e["id"]] = e
by_cat = {c["id"]: [p for p in projects if p["category"] == c["id"]] for c in cats}
total = len(projects)

def d(ts): return ts[:10] if ts else "–"
def status(p):
    e = ev.get(p["id"])
    if not e: return "not yet collected"
    return e.get("state", "unknown")
def lic(p):
    l = p["license"]
    return l["label"] + ("" if l["state"] == "declared" else " ⚠ needs review")

def w(path, text):
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    open(path, "w").write(text)

# ---- category pages
for c in cats:
    ps = by_cat[c["id"]]
    rows = "\n".join(f"| [{p['name']}](#{p['id'].replace('.', '')}) | {p['description']} | {p['editorial'].get('highlight','–')} | {', '.join(p['deployment'])} | {p['hardware']} | {lic(p)} | {status(p)} |" for p in ps)
    det = []
    for p in ps:
        e = ev.get(p["id"], {})
        rel = e.get("latest_release") or {}
        det.append(f"""### {p['name']} {{#{p['id'].replace('.', '')}}}

{p['description']}

| | |
|---|---|
| Upstream repository | [{p['name']} on GitHub]({p['repo']}) |
| Setup docs | [{p['name']} setup guide]({p['setup_url']}) |
| Licence | {lic(p)} · [licence evidence]({p['license']['evidence_url']}) · checked {p['license']['checked']} |
| Licence detected by GitHub | {e.get('license', {}).get('github_spdx') or 'not detected'} |
| Repository state | {status(p)} |
| Last commit | {d(e.get('last_commit'))} |
| Latest release | {rel.get('tag') or 'none detected'} {('(' + d(rel.get('published_at')) + ')') if rel else ''} |
| Deployment | {', '.join(p['deployment'])} |
| Hardware | {p['hardware']} |
| Languages | {', '.join(p['languages'])} |
| Evidence collected | {d(e.get('retrieved_at'))} |
""")
    w(f"docs/stacks/{c['id']}.md", f"""---
title: {c['title']} – Open Source Ai
description: {c['description']} Compare {len(ps)} open-source projects by licence, deployment and activity – CodesbyFebin Open Source Ai.
---
{GEN}
# {c['title']}

{c['description']}

*{len(ps)} projects · catalog last checked {max(p['last_checked'] for p in ps)}. "Highlight" is editorial; status, commit and release come from the [weekly evidence refresh](../freshness.md).*

## Comparison

| Project | What it does | Highlight (editorial) | Deployment | Hardware | Licence | Status |
|---|---|---|---|---|---|---|
{rows}

## Quick start

{quick[c['id']]}

## Project details

""" + "\n".join(det))

# ---- search data
data = []
for p in projects:
    e = ev.get(p["id"], {})
    data.append({"id": p["id"], "name": p["name"], "category": p["category"], "description": p["description"],
                 "tasks": p["tasks"], "deployment": p["deployment"], "hardware": p["hardware"], "languages": p["languages"],
                 "license": p["license"]["label"], "license_state": p["license"]["state"], "repo": p["repo"],
                 "status": status(p), "last_commit": d(e.get("last_commit"))})
w("docs/assets/catalog.json", json.dumps({"categories": [{"id": c["id"], "title": c["title"]} for c in cats], "projects": data}, indent=1, sort_keys=True) + "\n")

# ---- freshness report
fr = []
for p in projects:
    e = ev.get(p["id"], {})
    rel = (e.get("latest_release") or {}).get("tag") or "–"
    gl = e.get("license", {}).get("github_spdx") or "not detected"
    flags = []
    if status(p) == "archived": flags.append("archived")
    if e.get("canonical_repo") and e["canonical_repo"].lower() != p["repo"].lower(): flags.append("moved")
    if p["license"]["state"] != "declared" or gl in ("NOASSERTION", "not detected"): flags.append("licence review")
    if e.get("last_attempt"): flags.append("last fetch failed")
    fr.append(f"| [{p['name']}](stacks/{p['category']}.md#{p['id'].replace('.', '')}) | {status(p)} | {d(e.get('last_commit'))} | {rel} | {p['license']['label']} | {gl} | {d(e.get('retrieved_at'))} | {', '.join(flags) or '–'} |")
st = [status(p) for p in projects]
w("docs/freshness.md", f"""---
title: Freshness Report – Open Source Ai
description: Weekly evidence for every catalogued project – repository state, last commit, latest release and licence detection.
---
{GEN}
# Freshness Report

Evidence is collected from the public GitHub REST API by a **weekly** scheduled workflow (Mondays 03:00 UTC, also runnable manually). Changes arrive as a pull request for human review; nothing is rewritten on `main` automatically. This is not real-time monitoring.

**Summary:** {st.count('active')} active · {st.count('archived')} archived · {sum(1 for s in st if s not in ('active','archived'))} unknown/not collected · {total} total.

"Declared licence" is the curated value; "GitHub detected" is GitHub's automatic detection (`NOASSERTION` means GitHub could not identify a single licence). A failed request never marks a project deleted.

| Project | State | Last commit | Latest release | Declared licence | GitHub detected | Evidence date | Flags |
|---|---|---|---|---|---|---|---|
""" + "\n".join(fr) + "\n")

# ---- index / README
tbl = "\n".join(f"| [{c['title']}](stacks/{c['id']}.md) | {c['description']} | {len(by_cat[c['id']])} |" for c in cats)
w("docs/index.md", f"""---
title: Open Source Ai – Curated Catalog of Open-Source AI Agent & LLM Stacks
description: CodesbyFebin Open Source Ai is a curated, evidence-backed catalog of {total} open-source LLM gateways, chat UIs, local models, agents, RAG, memory and evaluation projects, with tested recipes.
---
{GEN}
# Open Source Ai

A **curated catalog** of open-source and source-available projects for building AI agents and LLM apps, maintained by **CodesbyFebin**. This repository contains metadata, comparisons and recipes – not upstream source code. Each project is owned and licensed by its own maintainers.

*{total} projects · {len(cats)} categories · evidence refreshed weekly ([freshness report](freshness.md))*

- 🔎 [Search & filter the catalog](catalog.md)
- 🧪 [Recipes](recipes/index.md) – composed stacks with honest test status
- 📏 [Selection criteria](selection-criteria.md)

| Category | What it covers | Projects |
|---|---|---|
{tbl}
""")
rt = "\n".join(f"| [{c['title']}](docs/stacks/{c['id']}.md) | {c['description']} | {len(by_cat[c['id']])} |" for c in cats)
w("README.md", f"""{GEN}<p align="center"><img src="docs/assets/favicon.svg" width="96" alt="Open Source Ai logo"></p>

# Open Source Ai by CodesbyFebin

A **curated, evidence-backed catalog** of open-source and source-available projects for AI agents and LLM apps: gateways, chat UIs, local models, inference servers, memory, agent frameworks, coding agents, code review, RAG and vector databases, evaluation, backends and templates.

This repo holds catalog data, comparisons and tested recipes. It does **not** bundle upstream code; every project stays with its own maintainers and licence.

📖 **Site:** {SITE} · 🔎 [Search & filter]({SITE}catalog/) · 🧪 [Recipes]({SITE}recipes/) · 📅 [Freshness report]({SITE}freshness/)

{total} projects · {len(cats)} categories · evidence refreshed weekly by pull request

| Category | What it covers | Projects |
|---|---|---|
{rt}

## Quick start

```bash
git clone https://github.com/CodesbyFebin/Open-Source-Ai
cd Open-Source-Ai/recipes/local-chat
docker compose up -d        # Ollama + LiteLLM + Open WebUI, see recipes/local-chat/README.md
```

## Contributing

Edit `catalog/projects.yaml` (never the generated pages), run `python scripts/build.py && python scripts/validate.py`, and open a PR. See [CONTRIBUTING.md](CONTRIBUTING.md).

## License

The MIT [LICENSE](LICENSE) © CodesbyFebin covers only this repository's own curation, docs and code. Upstream projects are governed by their own licences – see [CREDITS.md](CREDITS.md).
""")
cr = GEN + "# Credits & Licences\n\nOpen Source Ai's own content is MIT-licensed © CodesbyFebin. Catalogued projects are not included in this repository; each is governed by its upstream licence, which is authoritative. Entries marked **needs review** have custom, multiple or undetected licences – read the upstream terms before use.\n\n| Project | Upstream | Licence | State | Checked |\n|---|---|---|---|---|\n" + "\n".join(f"| {p['name']} | {p['repo']} | {p['license']['label']} | {p['license']['state']} | {p['license']['checked']} |" for p in projects) + "\n"
w("CREDITS.md", cr); w("docs/credits.md", cr.replace("](", "]("))

# ---- nav
m = open("mkdocs.yml").read().split("nav:")[0]
nav = "\n".join(f"      - {c['title']}: stacks/{c['id']}.md" for c in cats)
recipes = "\n".join(f"      - {yaml.safe_load(open(f))['title']}: recipes/{os.path.basename(os.path.dirname(f))}.md" for f in sorted(glob.glob("recipes/*/recipe.yaml")))
w("mkdocs.yml", m + f"""nav:
  - Home: index.md
  - Search & Filter: catalog.md
  - Recipes:
      - Overview: recipes/index.md
{recipes}
  - Guides:
      - Getting Started: guides/getting-started.md
      - Connect to a Gateway: guides/connect-gateway.md
  - Stacks:
{nav}
  - Freshness Report: freshness.md
  - Selection Criteria: selection-criteria.md
  - Credits & Licences: credits.md
""")

# ---- recipe pages
rows = []
for f in sorted(glob.glob("recipes/*/recipe.yaml")):
    r = yaml.safe_load(open(f)); rid = os.path.basename(os.path.dirname(f))
    body = open(os.path.join(os.path.dirname(f), "README.md")).read()
    t = r["test"]
    w(f"docs/recipes/{rid}.md", f"""---
title: {r['title']} – Open Source Ai recipe
description: {r['summary']}
---
{GEN}
!!! {'success' if t['status']=='tested' else 'warning'} "Test status: {t['status']}"
    {t['details']}

""" + body)
    rows.append(f"| [{r['title']}]({rid}.md) | {r['summary']} | **{t['status']}** |")
w("docs/recipes/index.md", f"{GEN}# Recipes\n\nRecipes compose a few catalogued projects into a working stack. Each states exactly what was tested, where and when. The catalog does not operate or support upstream software.\n\n| Recipe | What you get | Test status |\n|---|---|---|\n" + "\n".join(rows) + "\n")
print(f"built {total} projects, {len(ev)} evidence files")
